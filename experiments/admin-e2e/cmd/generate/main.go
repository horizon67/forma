package main

import (
	"flag"
	"fmt"
	"os"

	"github.com/horizon67/forma/experiments/admin-e2e/generator"
)

func main() {
	var options generator.Options
	flag.StringVar(&options.SourcePath, "source", "experiments/admin-e2e/app.forma", "Forma source file")
	flag.StringVar(&options.ProfilePath, "profile", "experiments/admin-e2e/profile.json", "experiment profile")
	flag.StringVar(&options.FixturesPath, "fixtures", "experiments/admin-e2e/fixtures.json", "E2E fixtures")
	flag.StringVar(&options.OutputPath, "out", ".forma-build/admin-e2e", "generated artifact directory")
	flag.BoolVar(&options.Force, "force", false, "replace an artifact previously generated by this profile")
	flag.Parse()

	if err := generator.Generate(options); err != nil {
		fmt.Fprintln(os.Stderr, "admin-e2e generate:", err)
		os.Exit(1)
	}
	fmt.Println("generated", options.OutputPath)
}
